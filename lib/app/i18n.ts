export const dictionaries: Record<Locale, Record<Key, string>> = { en, mk };

export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>) {
  let out: string = dictionaries[locale][key];
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export function useT() {
  const { locale } = useApp();
  const t = useCallback((key: Key, vars?: Record<string, string | number>) => translate(locale, key, vars), [locale]);
  return { t, locale };
}
